int	ft_find_next_prime(int nb)
{
	int	i;
	int	key;

	if (nb <= 1)
		nb = 2;
	while (1)
	{
		key = 1;
		i = 2;
		while (i < nb)
		{
			if (nb % i == 0)
			{
				key = 0;
				break ;
			}
			i++;
		}
		if (key == 1)
			return (nb);
		nb++;
	}
}
