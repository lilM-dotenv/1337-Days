int	ft_iterative_factorial(int nb)
{
	int	i;
	int	k;

	i = 0;
	k = 1;
	if (nb < 0)
		return (0);
	while (nb - i > 0)
	{
		k = k * (nb - i);
		i++;
	}
	return (k);
}
